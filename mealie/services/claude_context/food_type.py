def _normalize(text: str) -> str:
    text = text.lower().replace("œ", "oe").replace("æ", "ae").replace("’", "'")
    return "".join(c for c in unicodedata.normalize("NFD", text) if unicodedata.category(c) != "Mn")


# Longest keyword first, so "pomme de terre" beats "pomme" and "lait de coco" beats "lait".
_TABLE: list[tuple[re.Pattern[str], str]] = [
    (re.compile(rf"\b{re.escape(keyword)}"), kind)
    for keyword, kind in sorted(
        ((keyword, kind) for kind, keywords in _KEYWORDS.items() for keyword in keywords),
        key=lambda pair: -len(pair[0]),
    )
]


def food_type(name: str, label: str | None = None) -> str:
    """The food's label when it has one, else the type its name matches in the table, else "Autres"."""
    if label and label.strip():
        return label.strip()
    normalized = _normalize(name)
    for pattern, kind in _TABLE:
        if pattern.search(normalized):
            return kind
    return OTHER


def type_rank(kind: str) -> tuple[int, str]:
    """Sort key: the table's types in `TYPE_ORDER`, then the household's own labels by name, then "Autres"."""
    if kind in TYPE_ORDER:
        return (0, f"{TYPE_ORDER.index(kind):02d}")
    if kind == OTHER:
        return (2, "")
    return (1, _normalize(kind))
